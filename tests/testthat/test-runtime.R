test_that("session caches are independent, recoverable and cleaned up", {
  rt <- source_helpers("Runtime.R")
  a <- shiny::MockShinySession$new()
  b <- shiny::MockShinySession$new()
  on.exit({ a$close(); b$close() }, add = TRUE)
  pa <- rt$eb_session_workspace(a)
  pb <- rt$eb_session_workspace(b)
  expect_false(identical(pa, pb))
  expect_equal(rt$eb_cached_read(pa, "key", function() 1), 1)
  expect_equal(rt$eb_cached_read(pb, "key", function() 2), 2)
  rt$eb_clear_workspace(pa)
  expect_equal(rt$eb_cached_read(pb, "key", function() stop("should use cache")), 2)
  writeLines("broken", file.path(pa, "key.rds"))
  expect_equal(rt$eb_cached_read(pa, "key", function() 3), 3)
  a$close()
  expect_false(dir.exists(pa))
  expect_true(dir.exists(pb))
  b$close()
  expect_false(dir.exists(pb))
})

test_that("upload and PCA limits fail closed", {
  rt <- source_helpers("Runtime.R")
  withr::local_options(shiny.maxRequestSize = NULL)
  withr::local_envvar(c(EASYBREEDER_UPLOAD_MB = "12", EASYBREEDER_PCA_MEMORY_MB = "1",
                       EASYBREEDER_PCA_MAX_SAMPLES = "5000"))
  rt$eb_configure_uploads()
  expect_equal(getOption("shiny.maxRequestSize"), 12 * 1024^2)
  expect_error(rt$eb_check_pca_budget(100, 1000), "exceeds")
  expect_silent(rt$eb_check_pca_budget(2, 2))
  expect_error(rt$eb_check_pca_budget(NULL, NULL), "genotype matrix")
  withr::local_envvar(EASYBREEDER_PCA_MAX_COMPARISONS = "1")
  expect_error(rt$eb_check_pca_budget(2, 2), "computation limit")
  withr::local_envvar(EASYBREEDER_UPLOAD_MB = "unlimited")
  expect_error(rt$eb_configure_uploads(), "positive finite")
})
